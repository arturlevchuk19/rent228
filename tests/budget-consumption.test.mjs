import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const code = ts.transpile(readFileSync(new URL('../src/lib/budgetConsumption.ts', import.meta.url), 'utf8'), { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext });
const { calculateBudgetConsumption: total, parseConsumption: parse, formatConsumption: format } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const equipment = (quantity, power, peak_power) => ({ item_type: 'equipment', quantity, equipment: { power, peak_power } });
assert.deepEqual(total([]), { nominal: 0, maximum: 0 });
const categoryA = [equipment(3, '0,5', '0.8'), equipment(2, '1 кВт', '2 kW')];
const categoryB = [equipment(0.5, '2', '4'), { item_type: 'work', quantity: 20, equipment: { power: '50', peak_power: '100' } }];
const a = total(categoryA), b = total(categoryB), all = total([...categoryA, ...categoryB]);
assert.equal(a.nominal, 3.5);
assert.ok(Math.abs(a.maximum - 6.4) < 1e-10);
assert.equal(all.nominal, a.nominal + b.nominal);
assert.equal(all.maximum, a.maximum + b.maximum);
assert.deepEqual(total([equipment(2, '3', '0')]), { nominal: 6, maximum: 0 });
assert.deepEqual(total([equipment(2, '3', undefined)]), { nominal: 6, maximum: 6 });
assert.deepEqual(total([equipment(0, '3', '5'), equipment(-2, '3', '5'), equipment(Infinity, '3', '5'), {item_type: 'equipment', quantity: 5}]), { nominal: 0, maximum: 0 });
for (const value of [undefined, null, '', ' ', 'invalid', '-2', 'Infinity', '1/2', '2x3']) assert.equal(parse(value), 0);
assert.equal(parse(' 0,125 кВт '), 0.125);
assert.equal(format(1.23456), '1,235 кВт');
console.log('PASS: quantity totals, independent peak values, categories, decimals, missing and invalid data');
const { validateConsumptionInput: validate } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
for (const value of ['Физическое оборудование', 'Device', 'Part', 'Kit', 'Consumable']) {
  assert.equal(parse(value), 0);
  assert.throws(() => validate(value), /числом/);
}
assert.equal(validate(''), '0');
assert.equal(validate('  '), '0');
assert.equal(validate('0,015'), '0,015');
assert.equal(validate('1.2'), '1.2');
assert.throws(() => validate('-1'));
console.log('PASS: legacy descriptions become zero; invalid consumption input rejected');

import { supabase } from './supabase';
import { createBudgetItems, type BudgetItem } from './events';

/**
 * Single source of truth for the marker stored in `categories.description`
 * of the "Доп услуги" (extra services) category.
 */
export const EXTRA_SERVICE_CATEGORY_DESCRIPTION = '__extra_service__';

export interface Category {
  id: string;
  name: string;
  description: string;
  sort_order: number;
  is_template?: boolean;
  event_id?: string | null;
  created_at: string;
  updated_at: string;
}

export async function getCategories(): Promise<Category[]> {
  const { data, error } = await supabase
    .from('categories')
    .select('*')
    .is('event_id', null)
    .order('sort_order', { ascending: true })
    .order('name', { ascending: true });

  if (error) throw error;

  return data || [];
}

export async function getCategoriesForEvent(eventId: string): Promise<Category[]> {
  const { data, error } = await supabase
    .from('categories')
    .select('*')
    .eq('event_id', eventId)
    .order('sort_order', { ascending: true })
    .order('name', { ascending: true });

  if (error) throw error;

  return data || [];
}

export async function createCategory(name: string, description?: string, isTemplate: boolean = false, eventId?: string): Promise<Category> {
  if (!eventId) {
    const { data: existingCategories } = await supabase
      .from('categories')
      .select('*')
      .eq('name', name)
      .is('event_id', null);

    if (existingCategories && existingCategories.length > 0) {
      return existingCategories[0];
    }
  }

  const { data: lastCategory } = await supabase
    .from('categories')
    .select('sort_order')
    .order('sort_order', { ascending: false })
    .limit(1)
    .maybeSingle();

  const sortOrder = (lastCategory?.sort_order || 0) + 1;

  const insertData: Omit<Category, 'id' | 'created_at' | 'updated_at'> = {
    name,
    description: description || '',
    sort_order: sortOrder,
    is_template: isTemplate,
  };

  if (eventId) {
    insertData.event_id = eventId;
  }

  const { data, error } = await supabase
    .from('categories')
    .insert(insertData)
    .select()
    .single();

  if (error) throw error;

  return data;
}

export async function updateCategory(id: string, updates: Partial<Category>): Promise<Category> {
  const { data, error } = await supabase
    .from('categories')
    .update({ ...updates, updated_at: new Date().toISOString() })
    .eq('id', id)
    .select()
    .single();

  if (error) throw error;
  return data;
}

/**
 * Copies `source` as a new event-scoped category containing copies of `sourceItems`.
 * Ids are generated by the DB; totals are recomputed by the DB trigger (never copied).
 */
export async function duplicateCategory(
  source: Category,
  eventId: string,
  sourceItems: BudgetItem[],
  opts?: { isExtraService?: boolean }
): Promise<{ category: Category; items: BudgetItem[] }> {
  const existingCategories = await getCategoriesForEvent(eventId);
  const existingNames = existingCategories.map((item) => item.name.trim().toLowerCase());

  const baseName = `${source.name} (копия)`;
  let nextName = baseName;
  let index = 2;
  while (existingNames.includes(nextName.trim().toLowerCase())) {
    nextName = `${source.name} (копия ${index})`;
    index += 1;
  }

  const category = await createCategory(nextName, source.description, false, eventId);
  const isExtra = Boolean(opts?.isExtraService);

  const items: Partial<BudgetItem>[] = sourceItems.map((item) => ({
    event_id: eventId,
    category_id: category.id,
    equipment_id: item.equipment_id ?? null,
    work_item_id: item.work_item_id ?? null,
    modification_id: item.modification_id ?? null,
    item_type: item.item_type,
    quantity: item.quantity,
    price: item.price,
    notes: item.notes,
    exchange_rate: item.exchange_rate,
    multi_day_rate_override: item.multi_day_rate_override ?? null,
    location_id: item.location_id ?? null,
    sort_order: item.sort_order,
    unit: item.unit ?? null,
    name: item.name,
    sku: item.sku,
    marker_color: item.marker_color ?? null,
    is_extra: isExtra,
    picked: false,
    return_picked: false,
    parent_budget_item_id: null,
  }));

  const createdItems = await createBudgetItems(items);

  return { category, items: createdItems };
}

export async function deleteCategory(id: string): Promise<void> {
  const { error } = await supabase
    .from('categories')
    .delete()
    .eq('id', id);

  if (error) throw error;
}
